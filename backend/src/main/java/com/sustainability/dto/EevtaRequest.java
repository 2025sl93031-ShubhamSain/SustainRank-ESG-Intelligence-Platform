package com.sustainability.dto;

public class EevtaRequest {
    private String totalStudents;
    private String techVocStudents;
    private String distanceLearning;
    private String scholarshipStudents;
    private String financialAid;
    private String gradRate;
    private String employmentRate;
    private String femaleEnrolment;
    private String disabilityAccess;

    public EevtaRequest() {}
    public String getTotalStudents() { return totalStudents; }
    public void setTotalStudents(String v) { this.totalStudents = v; }
    public String getTechVocStudents() { return techVocStudents; }
    public void setTechVocStudents(String v) { this.techVocStudents = v; }
    public String getDistanceLearning() { return distanceLearning; }
    public void setDistanceLearning(String v) { this.distanceLearning = v; }
    public String getScholarshipStudents() { return scholarshipStudents; }
    public void setScholarshipStudents(String v) { this.scholarshipStudents = v; }
    public String getFinancialAid() { return financialAid; }
    public void setFinancialAid(String v) { this.financialAid = v; }
    public String getGradRate() { return gradRate; }
    public void setGradRate(String v) { this.gradRate = v; }
    public String getEmploymentRate() { return employmentRate; }
    public void setEmploymentRate(String v) { this.employmentRate = v; }
    public String getFemaleEnrolment() { return femaleEnrolment; }
    public void setFemaleEnrolment(String v) { this.femaleEnrolment = v; }
    public String getDisabilityAccess() { return disabilityAccess; }
    public void setDisabilityAccess(String v) { this.disabilityAccess = v; }
}
